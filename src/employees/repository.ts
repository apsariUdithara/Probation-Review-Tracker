import type { Queryable } from '../db.ts';

// SQL only, always parameterised. Every function takes companyId as its first data
// argument, and every WHERE / INSERT uses it: this is the application-level isolation.

export type EmployeeStatus = 'on_probation' | 'confirmed';

export type Employee = {
  id: string;
  companyId: string;
  name: string;
  joinDate: string;
  initialProbationMonths: number;
  totalProbationMonths: number;
  probationEndDate: string;
  status: EmployeeStatus;
  confirmedAt: Date | null;
  confirmedBy: string | null;
  createdAt: Date;
};

export type Extension = {
  id: string;
  months: number;
  reason: string;
  actor: string;
  previousEndDate: string;
  newEndDate: string;
  createdAt: Date;
};

export type AuditAction = 'employee.created' | 'probation.confirmed' | 'probation.extended';

type EmployeeRow = {
  id: string;
  company_id: string;
  name: string;
  join_date: string; // DATE comes back as 'YYYY-MM-DD' (type parser in db.ts)
  initial_probation_months: number;
  total_probation_months: number;
  probation_end_date: string;
  status: EmployeeStatus;
  confirmed_at: Date | null;
  confirmed_by: string | null;
  created_at: Date;
};

const EMPLOYEE_COLUMNS = `id, company_id, name, join_date, initial_probation_months,
  total_probation_months, probation_end_date, status, confirmed_at, confirmed_by, created_at`;

function toEmployee(row: EmployeeRow): Employee {
  return {
    id: row.id,
    companyId: row.company_id,
    name: row.name,
    joinDate: row.join_date,
    initialProbationMonths: row.initial_probation_months,
    totalProbationMonths: row.total_probation_months,
    probationEndDate: row.probation_end_date,
    status: row.status,
    confirmedAt: row.confirmed_at,
    confirmedBy: row.confirmed_by,
    createdAt: row.created_at,
  };
}

// initial = total = probationMonths; probation_end_date is generated by Postgres.
export async function insertEmployee(
  db: Queryable,
  companyId: string,
  input: { name: string; joinDate: string; probationMonths: number },
): Promise<Employee> {
  const { rows } = await db.query<EmployeeRow>(
    `INSERT INTO employees (company_id, name, join_date, initial_probation_months, total_probation_months)
     VALUES ($1, $2, $3, $4, $4)
     RETURNING ${EMPLOYEE_COLUMNS}`,
    [companyId, input.name, input.joinDate, input.probationMonths],
  );
  return toEmployee(rows[0]!);
}

export async function findEmployee(
  db: Queryable,
  companyId: string,
  id: string,
): Promise<Employee | undefined> {
  const { rows } = await db.query<EmployeeRow>(
    `SELECT ${EMPLOYEE_COLUMNS} FROM employees WHERE id = $1 AND company_id = $2`,
    [id, companyId],
  );
  return rows[0] && toEmployee(rows[0]);
}

export async function listExtensions(
  db: Queryable,
  companyId: string,
  employeeId: string,
): Promise<Extension[]> {
  const { rows } = await db.query<Extension>(
    `SELECT id, months, reason, actor,
            previous_end_date AS "previousEndDate", new_end_date AS "newEndDate", created_at AS "createdAt"
     FROM probation_extensions
     WHERE company_id = $1 AND employee_id = $2
     ORDER BY created_at, id`,
    [companyId, employeeId],
  );
  return rows;
}

export type OpenProbation = {
  id: string;
  name: string;
  joinDate: string;
  probationEndDate: string;
  totalProbationMonths: number;
  daysUntilEnd: number;
};

// Unconfirmed probations ending on or before today + withinDays. No lower bound, so overdue
// rows are always included. `today` is a parameter, never CURRENT_DATE (DB-timezone dependent).
// `status = 'on_probation'` is written literally so Postgres can use the partial index.
export async function listOpenProbations(
  db: Queryable,
  companyId: string,
  today: string,
  withinDays: number,
): Promise<OpenProbation[]> {
  const { rows } = await db.query<OpenProbation>(
    `SELECT id, name,
            join_date AS "joinDate",
            probation_end_date AS "probationEndDate",
            total_probation_months AS "totalProbationMonths",
            probation_end_date - $2::date AS "daysUntilEnd"  -- date - date = whole days
     FROM employees
     WHERE company_id = $1
       AND status = 'on_probation'
       AND probation_end_date <= $2::date + $3::int
     ORDER BY probation_end_date, name, id`,
    [companyId, today, withinDays],
  );
  return rows;
}

export async function insertAuditEvent(
  db: Queryable,
  companyId: string,
  event: { employeeId: string; action: AuditAction; actor: string; details: object },
): Promise<void> {
  await db.query(
    `INSERT INTO audit_events (company_id, employee_id, action, actor, details)
     VALUES ($1, $2, $3, $4, $5)`,
    [companyId, event.employeeId, event.action, event.actor, JSON.stringify(event.details)],
  );
}
